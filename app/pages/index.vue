                <h2 class="wp-block-heading"><strong>How Did L Bonds Work?</strong></h2>

                <p>Life insurance policyholders would sell their policies in the secondary market. For example, a
                    retiree could sell their $1 million policy to GWG for $250,000. This compensation would be greater
                    than that of the policy’s surrender value. As the new policyholder, GWG Holdings would handle the
                    premium payments–$30,000 per year and receive the $1 million payout from the insurer upon the death
                    of the original policyholder. L bonds financed these life insurance policy purchases.</p>

